
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_cliente_cpf
        CHECK (cpf ~ '^[0-9]{11}$'),

    CONSTRAINT chk_cliente_tipo
        CHECK (tipo IN ('CLIENTE', 'GERENTE'))
);

CREATE TABLE contas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_conta VARCHAR(20) NOT NULL UNIQUE,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    saldo NUMERIC(19,2) NOT NULL DEFAULT 0,
    cheque_especial_limite NUMERIC(19,2) NOT NULL DEFAULT 0,
    cheque_especial_utilizado NUMERIC(19,2) NOT NULL DEFAULT 0,
    divida_cheque_especial NUMERIC(19,2) NOT NULL DEFAULT 0,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_conta_saldo
        CHECK (saldo >= 0),

    CONSTRAINT chk_conta_limites
        CHECK (
            cheque_especial_limite >= 0
            AND cheque_especial_utilizado >= 0
            AND divida_cheque_especial >= 0
            AND cheque_especial_utilizado <= cheque_especial_limite
        )
);

CREATE TABLE transacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id BIGINT NOT NULL REFERENCES contas(id),
    tipo VARCHAR(30) NOT NULL,
    valor NUMERIC(19,2) NOT NULL,
    data_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    descricao VARCHAR(255),

    CONSTRAINT chk_transacao_valor
        CHECK (valor > 0)
);

CREATE INDEX idx_contas_cliente
    ON contas(cliente_id);

CREATE INDEX idx_transacoes_conta_data
    ON transacoes(conta_id, data_hora DESC);
