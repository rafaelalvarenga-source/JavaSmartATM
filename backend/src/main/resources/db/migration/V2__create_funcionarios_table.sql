
-- 1. Criar tabela exclusiva para funcionários
CREATE TABLE funcionarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(11) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    tipo_usuario VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL,

    CONSTRAINT uk_funcionarios_cpf UNIQUE (cpf),

    CONSTRAINT ck_funcionarios_tipo_usuario
        CHECK (tipo_usuario IN ('ATENDENTE', 'GERENTE'))
);

-- 2. Remover a antiga restrição de perfil dos clientes
ALTER TABLE clientes
    DROP CONSTRAINT ck_clientes_tipo_usuario;

-- 3. Remover o perfil de funcionário da tabela de clientes
ALTER TABLE clientes
    DROP COLUMN tipo_usuario;
